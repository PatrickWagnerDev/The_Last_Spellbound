/**
 * The state of the keys of the game: left, right, up, down, space, attack and fireball. Each one is true while
 * the key is pressed. The input scripts set the values, the character reads them.
 */
class Keyboard {
    LEFT = false;
    RIGHT = false;
    UP = false;
    DOWN = false;
    SPACE = false;
    ATTACK = false;
    SHOOT = false;
}
